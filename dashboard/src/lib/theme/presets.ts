/**
 * Presets: whole looks the admin can apply in one click, then keep editing.
 *
 * A preset only carries visual intent. Ordering, hidden sections and the
 * product's own name belong to the operator, not to a look, so applying a
 * preset leaves those alone.
 */

import { DEFAULT_THEME, type Theme } from "./tokens";

type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends readonly unknown[] ? T[K] : T[K] extends object ? DeepPartial<T[K]> : T[K];
};

