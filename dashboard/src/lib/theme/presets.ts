export const PRESET_IDS = PRESETS.map((p) => p.id);

function merge<T>(base: T, patch: unknown): T {
  if (patch === undefined) return base;
  if (Array.isArray(base) || patch === null || typeof patch !== "object" || typeof base !== "object" || base === null) {
    return patch as T;
  }
  const out = { ...(base as Record<string, unknown>) };
  for (const [key, value] of Object.entries(patch as Record<string, unknown>)) {
    out[key] = merge((base as Record<string, unknown>)[key], value);
  }
  return out as T;
}

/**
 * Applies a preset over the shipped defaults, then puts back the parts of the
 * current theme that describe the workspace rather than its appearance. Picking
 * a look should never rearrange the navigation or rename the product.
 */
export function applyPreset(current: Theme, presetId: string): Theme {
  const preset = PRESETS.find((p) => p.id === presetId);
  if (!preset) return current;
  const next = merge(DEFAULT_THEME, preset.theme) as Theme;
  return {
    ...next,
    preset: preset.id,
    layout: current.layout,
    brand: {
      ...next.brand,
      productName: current.brand.productName,
      wordmark: current.brand.wordmark,
      wordmarkAccent: current.brand.wordmarkAccent,
      tagline: current.brand.tagline,
    },
  };
}
